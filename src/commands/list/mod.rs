pub fn handle_list(
    repo: Repository,
    format: crate::OutputFormat,
    cli_branches: bool,
    cli_remotes: bool,
    cli_full: bool,
    progressive_flag: Option<bool>,
) -> anyhow::Result<()> {
    let render_target = RenderTarget::detect(format, progressive_flag);

    // A `.config/wt.toml` that doesn't parse reaches the listing only through
    // accessors that shrug it off (`[list] url`, `[forge] platform`), so it
    // would otherwise leave no trace on the command run most often. Warn
    // ahead of `collect()`, where those accessors run, so the line lands
    // above the rows instead of between them.
    repo.warn_if_project_config_unloadable();

    // Resolve the JSON schema before collecting, so an invalid-value warning
    // lands above the output rather than after a long collection.
    let json_schema =
        matches!(render_target, RenderTarget::Json).then(|| resolve_json_schema(&repo));

    let list_data = collect::collect(
        &repo,
        collect::ShowConfig::DeferredToParallel {
            cli_branches,
            cli_remotes,
            cli_full,
        },
        render_target,
        // Per-file mtimes feed only schema 2 JSON's `worktree.modified_at`;
        // table renders never read them, so they skip the
        // `--untracked-files=all` query and the mtime stat loop.
        json_schema == Some(2),
    )?;

    let Some(ListData {
        items,
        custom_columns,
        collected,
    }) = list_data
    else {
        return Ok(());
    };

    match json_schema {
        // Table modes already rendered inside `collect()`.
        None => {}
        Some(2) => print_json(&json_v2::to_json_envelope(
            &items,
            &custom_columns,
            &repo,
            collected,
        ))?,
        Some(_) => print_json(&json_output::to_json_items(&items, &custom_columns, &repo))?,
    }

    Ok(())
}

/// Resolve `[list] json-schema` (per-project resolved config) to 1 or 2.
///
/// Unset defaults to schema 2; an out-of-range value warns and defaults to
/// schema 2, matching how config load treats a
/// type error in the same key (warn and degrade, never brick a command).
/// The warning honors warning suppression because stderr would corrupt the
/// statusline consumer's prompt.
pub(crate) fn resolve_json_schema(repo: &Repository) -> u8 {
    use std::sync::Once;

    use color_print::cformat;
    use worktrunk::styling::warning_message;

    static WARNED: Once = Once::new();
    match repo.config().list.json_schema {
        Some(v @ (1 | 2)) => v,
        Some(other) => {
            WARNED.call_once(|| {
                if worktrunk::config::warnings_suppressed() {
                    return;
                }
                eprintln!(
                    "{}",
                    warning_message(cformat!(
                        "[list] json-schema is <bold>{other}</>, expected 1 or 2; using schema 2"
                    ))
                );
            });
            2
        }
        None => 2,
    }
}

#[derive(Default)]
pub(super) struct SummaryMetrics {
    worktrees: usize,
    local_branches: usize,
    remote_branches: usize,
    dirty_worktrees: usize,
    ahead_items: usize,
}

impl SummaryMetrics {
    pub(super) fn from_items(items: &[ListItem]) -> Self {
        let mut metrics = Self::default();
        for item in items {
            metrics.update(item);
        }
        metrics
    }

    fn update(&mut self, item: &ListItem) {
        if let Some(_data) = item.worktree_data() {
            self.worktrees += 1;
            // Use status_symbols.working_tree which includes untracked files,
            // not just working_tree_diff which only has tracked changes.
            // `None` means gate 1 hasn't resolved yet — don't count.
            if item
                .status_symbols
                .working_tree
                .is_some_and(|wt| wt.is_dirty())
            {
                self.dirty_worktrees += 1;
            }
        } else {
            // Local vs remote is recorded structurally on the item
            // (`BranchScope`), never inferred from the name — a local branch
            // may legitimately be named `origin/foo`, so a name-prefix
            // heuristic would misclassify it. See `BranchScope` in
            // `model/item.rs`.
            match item.kind() {
                ItemKind::Branch(BranchScope::Remote) => self.remote_branches += 1,
                _ => self.local_branches += 1,
            }
        }

        if item.counts.is_some_and(|c| c.ahead > 0) {
            self.ahead_items += 1;
        }
    }

    pub(super) fn inventory_parts(&self, include_branches: bool) -> Vec<String> {
        let mut parts = Vec::new();

        let plural = if self.worktrees == 1 { "" } else { "s" };
        parts.push(format!("{} worktree{}", self.worktrees, plural));

        if include_branches {
            if self.local_branches > 0 {
                let plural = if self.local_branches == 1 { "" } else { "es" };
                parts.push(format!("{} branch{}", self.local_branches, plural));
            }
            if self.remote_branches > 0 {
                let plural = if self.remote_branches == 1 { "" } else { "es" };
                parts.push(format!("{} remote branch{}", self.remote_branches, plural));
            }
        }

        parts
    }

    pub(super) fn summary_parts(
        &self,
        include_branches: bool,
        hidden_columns: &[String],
    ) -> Vec<String> {
        let mut parts = self.inventory_parts(include_branches);

        if self.dirty_worktrees > 0 {
            parts.push(format!("{} with changes", self.dirty_worktrees));
        }

        if self.ahead_items > 0 {
            parts.push(format!("{} ahead", self.ahead_items));
        }

        if !hidden_columns.is_empty() {
            parts.push(format!("hidden: {}", hidden_columns.join(", ")));
        }

        parts
    }
}

/// One cache file shared by all worktrees of the repository.
pub(crate) fn status_explanations_path(repo: &worktrunk::git::Repository) -> std::path::PathBuf {
    worktrunk::cache::cache_dir(repo, "status-explanations").join("shown.json")
}

pub(crate) type ShownExplanations = std::collections::BTreeSet<String>;

/// Add unseen pairs in priority order. A pair that cannot fit on its own
/// does not hold the current cycle open at this width.
fn status_legend(
    items: &[ListItem],
    mut remaining: usize,
    shown: &mut ShownExplanations,
) -> Vec<String> {
    let mut visible = std::collections::HashSet::new();
    let mut eligible: Vec<_> = items
        .iter()
        .flat_map(|item| item.status_symbols.explanations())
        .filter_map(|(attention, pair)| {
            let width = visual_width(&pair);
            (width <= remaining && visible.insert(pair.clone())).then_some((attention, pair, width))
        })
        .collect();
    if eligible.is_empty() {
        return Vec::new();
    }
    if eligible.iter().all(|(_, pair, _)| shown.contains(pair)) {
        shown.clear();
    }

    eligible.sort_by_key(|(attention, _, _)| !attention);
    let mut legend = Vec::new();
    for (_, pair, width) in eligible {
        let cost = width + if legend.is_empty() { 0 } else { 2 };
        if cost <= remaining && shown.insert(pair.clone()) {
            remaining -= cost;
            legend.push(pair);
        }
    }
    legend
}

/// Format the summary line that closes the table.
///
/// The footer is the only home a timed-out task has: it leaves an empty cell
/// and no message to print, so the count here is all that reports it. Tasks
/// that failed instead get a named entry in the warning that follows the
/// table, and that warning carries its own count — repeating it here would
/// print the same number twice on adjacent lines.
///
/// `max_width` bounds the line, following [`format_with_gutter`]'s
/// convention. An undetectable width wraps nothing and omits the legend.
/// Long summaries wrap, with continuations aligned under the text. The
/// explanations use the width of their own line.
///
/// [`format_with_gutter`]: worktrunk::styling::format_with_gutter
pub(crate) fn format_summary_message(
    items: &[ListItem],
    show_branches: bool,
    hidden_columns: &[String],
    timed_out_count: usize,
    shown: Option<&mut ShownExplanations>,
    max_width: Option<usize>,
) -> String {
    const INDENT: &str = "  "; // symbol + space, so continuations align under the text
    const LEGEND_PREFIX: &str = "↳ ";

    let metrics = SummaryMetrics::from_items(items);
    let dim = Style::new().dimmed();
    let summary = metrics
        .summary_parts(show_branches, hidden_columns)
        .join(", ");

    let body = if timed_out_count > 0 {
        let plural = if timed_out_count == 1 { "" } else { "s" };
        format!("Showing {summary}; {timed_out_count} task{plural} timed out")
    } else {
        format!("Showing {summary}")
    };

    let mut body = wrap_styled_text(
        &body,
        max_width.unwrap_or(usize::MAX).saturating_sub(INDENT.len()),
    )
    .iter()
    // The wrapper keeps the space it broke on, which would land a
    // continuation one column right of the indent.
    .map(|line| line.trim())
    .collect::<Vec<_>>()
    .join(&format!("\n{INDENT}"));

    if let (Some(shown), Some(width)) = (shown, max_width) {
        let budget = width.saturating_sub(visual_width(LEGEND_PREFIX));
        let legend = status_legend(items, budget, shown);
        if !legend.is_empty() {
            body.push('\n');
            body.push_str(LEGEND_PREFIX);
            body.push_str(&legend.join("  "));
        }
    }
    format!("{INFO_SYMBOL} {dim}{body}{dim:#}")
}

